// Re-canonicalize existing pantry_item + recipe_ingredient rows against the CURRENT synonym map.
// Use this after extending SYNONYMS in src/canonicalize.js so rows that were canonicalized under
// an older (narrower) map get updated to the new canonical form.
//
// This ONLY emits UPDATEs for rows whose canonical_name would actually change — skips no-ops.
//
// Usage:
//   cd backend
//   node ingest/resync-canonical.js
//   npx wrangler d1 execute pantrie-db-staging --remote --file=ingest/resync-canonical.sql
//
// Scope: pantry_item + recipe_ingredient. shopping_item is deliberately NOT resynced.

import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { canonicalize } from '../src/canonicalize.js';

const BACKEND_DIR = fileURLToPath(new URL('../', import.meta.url));
const OUT = fileURLToPath(new URL('./resync-canonical.sql', import.meta.url));
const DB = 'pantrie-db-staging';

function sqlEscape(s) {
  return String(s ?? '').replace(/'/g, "''");
}

function queryJson(sql) {
  const cmd = `npx wrangler d1 execute ${DB} --remote --json --command "${sql.replace(/"/g, '\\"')}"`;
  const out = execSync(cmd, { cwd: BACKEND_DIR, maxBuffer: 500_000_000 }).toString();
  const data = JSON.parse(out);
  return data?.[0]?.results || [];
}

function main() {
  console.log(`Reading recipe_ingredient rows from ${DB}...`);
  const recIngs = queryJson('SELECT recipe_id, seq, name, canonical_name FROM recipe_ingredient');
  console.log(`  ${recIngs.length} total rows`);

  console.log('Reading pantry_item rows...');
  const pantry = queryJson('SELECT id, name, canonical_name FROM pantry_item');
  console.log(`  ${pantry.length} total rows`);

  const lines = [
    '-- Auto-generated by ingest/resync-canonical.js',
    '-- Re-canonicalizes rows whose canonical_name differs under the current SYNONYMS map.',
    '-- Safe to re-run: no-op rows are skipped at generation time.',
    '',
  ];

  let recChanged = 0;
  for (const r of recIngs) {
    const canon = canonicalize(r.name);
    if (!canon) continue;
    if (canon === r.canonical_name) continue;
    lines.push(
      `UPDATE recipe_ingredient SET canonical_name = '${sqlEscape(canon)}' ` +
      `WHERE recipe_id = '${sqlEscape(r.recipe_id)}' AND seq = ${Number(r.seq)};`
    );
    recChanged++;
  }

  let pantryChanged = 0;
  for (const p of pantry) {
    const canon = canonicalize(p.name);
    if (!canon) continue;
    if (canon === p.canonical_name) continue;
    lines.push(
      `UPDATE pantry_item SET canonical_name = '${sqlEscape(canon)}' ` +
      `WHERE id = '${sqlEscape(p.id)}';`
    );
    pantryChanged++;
  }

  writeFileSync(OUT, lines.join('\n') + '\n', 'utf8');
  console.log('');
  console.log(`  recipe_ingredient UPDATEs: ${recChanged}`);
  console.log(`  pantry_item UPDATEs:       ${pantryChanged}`);
  console.log(`  total UPDATEs:             ${recChanged + pantryChanged}`);
  console.log(`  wrote -> ${OUT}`);
  console.log('');
  console.log(`Next: npx wrangler d1 execute ${DB} --remote --file=ingest/resync-canonical.sql`);
}

main();
